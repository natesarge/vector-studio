// Converts the official @visioncortex/vtracer package (built for Node.js) into
// a browser-friendly ES module in src/vendor/vtracer/. Re-run after upgrading
// the package:   node scripts/vendor-vtracer.mjs
//
// The package's loader reads the .wasm file with Node's "fs". We swap that tail
// for an init() function that receives the wasm bytes, and turn the CommonJS
// exports into ES exports. Nothing else is changed.
import { readFileSync, writeFileSync, copyFileSync } from "node:fs";

const src = "node_modules/@visioncortex/vtracer/";
const out = "src/vendor/vtracer/";
const version = JSON.parse(readFileSync(src + "package.json", "utf8")).version;

let js = readFileSync(src + "pkg/vtracer_wasm.js", "utf8");
const tailStart = js.indexOf("const wasmPath =");
if (tailStart < 0 || !js.includes("exports.vectorize_rgba = vectorize_rgba;")) {
  throw new Error("vtracer loader layout changed; update scripts/vendor-vtracer.mjs");
}
js = js.slice(0, tailStart).replace(/^exports\.\w+ = \w+;\r?\n/gm, "");
js =
  `// GENERATED by scripts/vendor-vtracer.mjs from @visioncortex/vtracer ${version}\n` +
  `// (c) visioncortex contributors, licensed MIT OR Apache-2.0. Do not edit by hand.\n` +
  js +
  `
let wasm;

/** Load the WebAssembly module. Call once before vectorize_*. */
export async function initVtracer(wasmUrl) {
  if (wasm) return;
  const bytes = await (await fetch(wasmUrl)).arrayBuffer();
  const { instance } = await WebAssembly.instantiate(bytes, __wbg_get_imports());
  wasm = instance.exports;
  wasm.__wbindgen_start();
}

export { vectorize_bytes, vectorize_rgba };
`;
writeFileSync(out + "vtracer_wasm.js", js);
writeFileSync(
  out + "vtracer_wasm.d.ts",
  `export function initVtracer(wasmUrl: string): Promise<void>;
export function vectorize_bytes(data: Uint8Array, options: unknown): string;
export function vectorize_rgba(data: Uint8Array, width: number, height: number, options: unknown): string;
`,
);
copyFileSync(src + "pkg/vtracer_wasm_bg.wasm", out + "vtracer_wasm_bg.wasm");
console.log("vendored vtracer " + version);
